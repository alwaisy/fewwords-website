<script setup lang="ts">
import { useErrorMessage } from "./composables/use-error-message";
import { useSummaryProcessing } from "./composables/use-summary-processing";

const route = useRoute();
const router = useRouter();
const summaryId = route.params.summaryId as string;

// Check for reader mode via query param
const isReaderMode = computed(
  () => "r" in route.query || "reader" in route.query,
);

// Fetch summary data from API
const {
  data: summary,
  pending,
  error,
  refresh,
} = await useFetch(`/api/summary/${summaryId}`);

// Get the display title
const displayTitle = computed(() => {
  return (
    summary.value?.title || `${summary.value?.essence || "Content"} Summary`
  );
});

// Get user-friendly error message
const { getFriendlyErrorMessage } = useErrorMessage();
const friendlyErrorMessage = computed(() =>
  getFriendlyErrorMessage(summary.value?.errorMessage || ""),
);

// Summary processing logic
const {
  currentMessage,
  currentIcon,
  startProcessing,
  watchStatusChanges,
  currentStage,
  stageProgress,
  getStages,
  getCurrentStageIndex,
} = useSummaryProcessing(summary, refresh);

// Update meta tags when summary is loaded
watchEffect(() => {
  if (summary.value?.status === "completed" && summary.value.title) {
    useHead({
      title: `${summary.value.title} - Fewwords`,
      titleTemplate: null,
      meta: [
        {
          name: "description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:title",
          content: summary.value.title,
        },
        {
          property: "og:description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:type",
          content: "article",
        },
      ],
    });
  }
});

function copyLink() {
  navigator.clipboard.writeText(window.location.href);
  useToastify("Link copied!");
}

function openSource() {
  if (summary.value?.source) {
    window.open(summary.value.source, "_blank", "noopener,noreferrer");
  }
}

function saveSummary() {
  useToastify("Saved!");
}

function doAnother() {
  router.push("/app");
}

// Start processing on mount if pending
onMounted(() => {
  if (summary.value?.status === "pending") {
    startProcessing();
  }
});

// Watch for status changes (for poll/retry scenarios)
watchStatusChanges();
</script>

<template>
  <main class="flex-1">
    <article class="py-12 px-4">
      <div class="max-w-2xl mx-auto">
        <!-- Initial Load Skeleton -->
        <AppSummarySkeleton v-if="pending" />

        <!-- Error State -->
        <div v-else-if="error" class="text-center py-20">
          <div
            class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
          >
            <Icon name="lucide:ghost" size="3rem" class="text-primary" />
          </div>
          <h1 class="text-2xl font-bold text-foreground mb-3">
            Well, this is awkward
          </h1>
          <p class="text-muted-foreground mb-8 max-w-md mx-auto">
            The summary went into hiding. Maybe it exists in another dimension?
          </p>
          <Button variant="outline" @click="doAnother">Try another URL</Button>
        </div>

        <!-- Processing State (pending or processing) -->
        <div
          v-else-if="
            summary &&
            (summary.status === 'pending' || summary.status === 'processing')
          "
          class="text-center py-20"
        >
          <div
            class="w-16 h-16 mx-auto mb-6 relative flex items-center justify-center"
          >
            <div class="absolute inset-0 rounded-full border-2 border-primary/20" />
            <div class="absolute inset-0 rounded-full border-2 border-transparent border-t-primary animate-spin" />
            <Icon
              :name="currentIcon"
              size="3rem"
              class="text-primary"
            />
          </div>

          <h1 class="text-xl font-medium text-foreground mb-2">
            {{ currentMessage }}
          </h1>

          <p class="text-sm text-muted-foreground mb-8">
            {{ summary.essence === 'youtube' ? 'Long videos take 3-4 minutes' : 'This usually takes about 15-20 seconds' }}
          </p>

          <!-- Stage Progress for YouTube -->
          <div
            v-if="summary.essence === 'youtube' && getStages.length > 0"
            class="max-w-md mx-auto"
          >
            <div class="space-y-4">
              <div
                v-for="(stage, index) in getStages"
                :key="stage.stage"
                class="flex items-center gap-3 text-left"
                :class="{
                  'opacity-100': index <= getCurrentStageIndex,
                  'opacity-40': index > getCurrentStageIndex,
                }"
              >
                <!-- Stage Icon -->
                <div class="relative">
                  <div
                    class="w-10 h-10 rounded-full flex items-center justify-center"
                    :class="{
                      'bg-primary/10': index <= getCurrentStageIndex,
                      'bg-muted': index > getCurrentStageIndex,
                    }"
                  >
                    <Icon
                      :name="stage.icon"
                      size="1.25rem"
                      :class="{
                        'text-primary': index <= getCurrentStageIndex,
                        'text-muted-foreground': index > getCurrentStageIndex,
                      }"
                    />
                  </div>
                  
                  <!-- Current Stage Spinner -->
                  <div
                    v-if="currentStage === stage.stage"
                    class="absolute inset-0 rounded-full border-2 border-transparent border-t-primary animate-spin"
                  />
                </div>

                <!-- Stage Info -->
                <div class="flex-1">
                  <p class="text-sm font-medium text-foreground">
                    {{ stage.message }}
                  </p>
                  
                  <!-- Progress Bar for Current Stage -->
                  <div
                    v-if="currentStage === stage.stage"
                    class="mt-2 h-1.5 bg-muted rounded-full overflow-hidden"
                  >
                    <div
                      class="h-full bg-primary transition-all duration-300 ease-out"
                      :style="{ width: `${stageProgress}%` }"
                    />
                  </div>
                  
                  <!-- Completed Check -->
                  <div v-else-if="index < getCurrentStageIndex" class="mt-1">
                    <Icon
                      name="lucide:check-circle"
                      size="1rem"
                      class="text-green-500"
                    />
                  </div>
                </div>

                <!-- Stage Time -->
                <div class="text-xs text-muted-foreground w-16 text-right">
                  ~{{ Math.round((stage.maxTime - stage.minTime)) }}s
                </div>
              </div>
            </div>
          </div>
        </div>

        <!-- Failed State -->
        <div
          v-else-if="summary && summary.status === 'failed'"
          class="text-center py-20"
        >
          <div
            class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
          >
            <Icon name="lucide:zap-off" size="2.5rem" class="text-primary" />
          </div>
          <h1 class="text-2xl font-bold text-foreground mb-3">
            Well, that didn't work
          </h1>
          <p class="text-muted-foreground mb-8 max-w-md mx-auto">
            {{ friendlyErrorMessage }}
          </p>
          <div class="flex gap-3 justify-center">
            <Button variant="outline" @click="doAnother"
              >Try another URL</Button
            >
          </div>
        </div>

        <!-- Completed State -->
        <template v-else-if="summary && summary.status === 'completed'">
          <AppSummaryHeader
            :title="displayTitle"
            :source-url="summary.source"
            :reader-mode="isReaderMode"
            @share="copyLink"
            @open-source="openSource"
            @save="saveSummary"
          />
          <AppSummaryContent
            :content="summary.summary ?? ''"
            :source-url="summary.source"
          />
          <AppSummaryFooter
            :reader-mode="isReaderMode"
            @do-another="doAnother"
          />
        </template>
      </div>
    </article>
  </main>
</template>
