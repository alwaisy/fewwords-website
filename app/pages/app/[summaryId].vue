<script setup lang="ts">
const route = useRoute();
const router = useRouter();
const summaryId = route.params.summaryId as string;

// Check for reader mode via query param
const isReaderMode = computed(
  () => "r" in route.query || "reader" in route.query,
);

// Fetch summary data from API
const {
  data: summary,
  pending,
  error,
  refresh,
} = await useFetch(`/api/summary/${summaryId}`);

// Get the display title
const displayTitle = computed(() => {
  return (
    summary.value?.title || `${summary.value?.essence || "Content"} Summary`
  );
});

// Get user-friendly error message
const friendlyErrorMessage = computed(() => {
  const raw = summary.value?.errorMessage || "";

  // Jina API errors
  if (raw.includes("500") || raw.includes("Internal Server Error")) {
    return "The content is temporarily unavailable. Please try again.";
  }
  if (raw.includes("Failed to fetch")) {
    return "Could not retrieve the content. The URL may be invalid or inaccessible.";
  }
  if (raw.includes("timeout") || raw.includes("timed out")) {
    return "Request took too long. Please try again.";
  }

  // YouTube errors
  if (raw.includes("YouTube") || raw.includes("video")) {
    return "Could not process this video. It may be private or unavailable.";
  }

  // Generic fallback
  return "Something went wrong. Please try again with a different URL.";
});

// Update meta tags when summary is loaded
watchEffect(() => {
  if (summary.value?.status === "completed" && summary.value.title) {
    useHead({
      title: `${summary.value.title} - Fewwords`,
      titleTemplate: null,
      meta: [
        {
          name: "description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:title",
          content: summary.value.title,
        },
        {
          property: "og:description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:type",
          content: "article",
        },
      ],
    });
  }
});

function copyLink() {
  navigator.clipboard.writeText(window.location.href);
  useToastify("Link copied!");
}

function openSource() {
  if (summary.value?.source) {
    window.open(summary.value.source, "_blank", "noopener,noreferrer");
  }
}

function saveSummary() {
  useToastify("Saved!");
}

function doAnother() {
  router.push("/app");
}

// Loading messages for processing state
const loadingMessages = [
  "Thinking...",
  "Researching...",
  "Reading...",
  "Extracting...",
  "Writing...",
  "Analyzing...",
  "Processing...",
  "Synthesizing...",
  "Comprehending...",
  "Summarizing...",
  "Digesting...",
  "Understanding...",
  "Evaluating...",
  "Structuring...",
];

const currentMessage = ref<string>("");

function getRandomMessage(): string {
  const index = Math.floor(Math.random() * loadingMessages.length);
  return loadingMessages[index]!;
}

// Watch for status changes and handle pending/processing
watchEffect(async () => {
  if (
    summary.value?.status === "pending" &&
    summary.value?.source &&
    summary.value?.summaryId
  ) {
    // Start processing - call the original API
    currentMessage.value = getRandomMessage();

    // Cycle messages
    const interval = setInterval(() => {
      currentMessage.value = getRandomMessage();
    }, 1500);

    try {
      await $fetch("/api/summarize", {
        method: "POST",
        body: {
          url: summary.value.source,
          updateSummaryId: summary.value.summaryId,
        },
      });
      clearInterval(interval);
      await refresh(); // Refresh to get updated data
    } catch {
      clearInterval(interval);
      await refresh(); // Refresh even on error to show failed status
    }
  } else if (summary.value?.status === "processing") {
    // Poll for updates every 2 seconds
    const pollInterval = setInterval(async () => {
      await refresh();
      if (summary.value?.status !== "processing") {
        clearInterval(pollInterval);
      }
    }, 2000);

    // Cleanup on unmount
    onUnmounted(() => clearInterval(pollInterval));
  }
});
</script>

<template>
  <main class="flex-1">
    <article class="py-12 px-4">
      <div class="max-w-2xl mx-auto">
        <!-- Initial Load Skeleton -->
        <AppSummarySkeleton v-if="pending" />

        <!-- Error State -->
        <div v-else-if="error" class="text-center py-20">
          <p class="text-destructive mb-4">Failed to load summary</p>
          <Button variant="outline" @click="doAnother">Go back</Button>
        </div>

        <!-- Processing State (pending or processing) -->
        <div
          v-else-if="
            summary &&
            (summary.status === 'pending' || summary.status === 'processing')
          "
          class="text-center py-20"
        >
          <div
            class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
          >
            <Icon
              name="lucide:loader-2"
              class="w-10 h-10 text-primary animate-spin"
            />
          </div>

          <h1 class="text-2xl font-bold text-foreground mb-2 animate-pulse">
            {{ currentMessage }}
          </h1>
          <p class="text-muted-foreground mb-8">
            This usually takes about 15-20 seconds
          </p>
        </div>

        <!-- Failed State -->
        <div
          v-else-if="summary && summary.status === 'failed'"
          class="text-center py-20"
        >
          <div
            class="w-16 h-16 mx-auto mb-4 rounded-full bg-destructive/10 flex items-center justify-center"
          >
            <Icon name="lucide:alert-circle" class="w-8 h-8 text-destructive" />
          </div>
          <h1 class="text-xl font-bold text-foreground mb-2">
            Processing Failed
          </h1>
          <p class="text-muted-foreground mb-6">{{ friendlyErrorMessage }}</p>
          <Button variant="outline" @click="doAnother">Try again</Button>
        </div>

        <!-- Completed State -->
        <template v-else-if="summary && summary.status === 'completed'">
          <AppSummaryHeader
            :title="displayTitle"
            :source-url="summary.source"
            :reader-mode="isReaderMode"
            @share="copyLink"
            @open-source="openSource"
            @save="saveSummary"
          />
          <AppSummaryContent :content="summary.summary ?? ''" />
          <AppSummaryFooter
            :reader-mode="isReaderMode"
            @do-another="doAnother"
          />
        </template>
      </div>
    </article>
  </main>
</template>
