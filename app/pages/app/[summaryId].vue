<script setup lang="ts">
import { useErrorMessage } from "./composables/use-error-message";
import { useSummaryProcessing } from "./composables/use-summary-processing";

const route = useRoute();
const router = useRouter();
const summaryId = route.params.summaryId as string;

// Check for reader mode via query param
const isReaderMode = computed(
  () => "r" in route.query || "reader" in route.query,
);

// Fetch summary data from API
const {
  data: summary,
  pending,
  error,
  refresh,
} = await useFetch(`/api/summary/${summaryId}`);

// Get the display title
const displayTitle = computed(() => {
  return (
    summary.value?.title || `${summary.value?.essence || "Content"} Summary`
  );
});

// Get user-friendly error message
const { getFriendlyErrorMessage } = useErrorMessage();
const friendlyErrorMessage = computed(() =>
  getFriendlyErrorMessage(summary.value?.errorMessage || ""),
);

// Summary processing logic
const { currentMessage, currentStage, stageInfo, startProcessing, watchStatusChanges } = useSummaryProcessing(summary, refresh);

// Update meta tags when summary is loaded
watchEffect(() => {
  if (summary.value?.status === "completed" && summary.value.title) {
    useHead({
      title: `${summary.value.title} - Fewwords`,
      titleTemplate: null,
      meta: [
        {
          name: "description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:title",
          content: summary.value.title,
        },
        {
          property: "og:description",
          content:
            summary.value.summary?.slice(0, 160) ||
            "Summary generated by Fewwords",
        },
        {
          property: "og:type",
          content: "article",
        },
      ],
    });
  }
});

function copyLink() {
  navigator.clipboard.writeText(window.location.href);
  useToastify("Link copied!");
}

function openSource() {
  if (summary.value?.source) {
    window.open(summary.value.source, "_blank", "noopener,noreferrer");
  }
}

function saveSummary() {
  useToastify("Saved!");
}

function doAnother() {
  router.push("/app");
}

// Start processing on mount if pending
onMounted(() => {
  if (summary.value?.status === "pending") {
    startProcessing();
  }
});

// Watch for status changes (for poll/retry scenarios)
watchStatusChanges();
</script>

<template>
  <main class="flex-1">
    <article class="py-12 px-4">
      <div class="max-w-2xl mx-auto">
        <!-- Initial Load Skeleton -->
        <AppSummarySkeleton v-if="pending" />

        <!-- Error State -->
        <div v-else-if="error" class="text-center py-20">
          <div
            class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
          >
            <Icon name="lucide:ghost" class="w-10 h-10 text-primary" />
          </div>
          <h1 class="text-2xl font-bold text-foreground mb-3">
            Well, this is awkward
          </h1>
          <p class="text-muted-foreground mb-8 max-w-md mx-auto">
            The summary went into hiding. Maybe it exists in another dimension?
          </p>
          <Button variant="outline" @click="doAnother">Try another URL</Button>
        </div>

        <!-- Processing State (pending or processing) -->
        <div
          v-else-if="
            summary &&
            (summary.status === 'pending' || summary.status === 'processing')
          "
          class="text-center py-20"
        >
          <!-- YouTube-specific 3-stage loading -->
          <div v-if="summary.essence === 'youtube'" class="space-y-8">
            <!-- Stage indicators -->
            <div class="flex justify-center gap-3 mb-8">
              <div
                v-for="stage in 3"
                :key="stage"
                class="w-3 h-3 rounded-full transition-all duration-500"
                :class="
                  stage <= currentStage
                    ? 'bg-primary scale-110'
                    : 'bg-muted'
                "
              />
            </div>

            <!-- Animated icon -->
            <div
              class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
            >
              <Icon
                :name="
                  currentStage === 1
                    ? 'lucide:play-circle'
                    : currentStage === 2
                      ? 'lucide:brain'
                      : 'lucide:sparkles'
                "
                class="w-10 h-10 text-primary"
                :class="{ 'animate-pulse': currentStage < 3 }"
              />
            </div>

            <h1 class="text-2xl font-bold text-foreground mb-2">
              {{ currentMessage }}
            </h1>

            <p class="text-muted-foreground mb-4">
              {{ stageInfo }}
            </p>

            <!-- Stage descriptions -->
            <div class="max-w-md mx-auto text-sm text-muted-foreground space-y-2">
              <p v-if="currentStage === 1" class="animate-in fade-in slide-in-from-bottom-2 duration-500">
                Stage 1 of 3: Getting video info from YouTube
              </p>
              <p v-else-if="currentStage === 2" class="animate-in fade-in slide-in-from-bottom-2 duration-500">
                Stage 2 of 3: Watching and classifying the content
              </p>
              <p v-else-if="currentStage === 3" class="animate-in fade-in slide-in-from-bottom-2 duration-500">
                Stage 3 of 3: Writing your summary
              </p>
            </div>
          </div>

          <!-- Article/Reddit generic loading -->
          <div v-else class="space-y-6">
            <div
              class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
            >
              <Icon
                name="lucide:loader-2"
                class="w-10 h-10 text-primary animate-spin"
              />
            </div>

            <h1 class="text-2xl font-bold text-foreground mb-2 animate-pulse">
              {{ currentMessage }}
            </h1>
            <p class="text-muted-foreground">
              This usually takes about 15-20 seconds
            </p>
          </div>
        </div>

        <!-- Failed State -->
        <div
          v-else-if="summary && summary.status === 'failed'"
          class="text-center py-20"
        >
          <div
            class="w-20 h-20 mx-auto mb-6 rounded-full bg-primary/10 flex items-center justify-center"
          >
            <Icon name="lucide:zap-off" class="w-10 h-10 text-primary" />
          </div>
          <h1 class="text-2xl font-bold text-foreground mb-3">
            Well, that didn't work
          </h1>
          <p class="text-muted-foreground mb-8 max-w-md mx-auto">
            {{ friendlyErrorMessage }}
          </p>
          <div class="flex gap-3 justify-center">
            <Button variant="outline" @click="doAnother">Try another URL</Button>
          </div>
        </div>

        <!-- Completed State -->
        <template v-else-if="summary && summary.status === 'completed'">
          <AppSummaryHeader
            :title="displayTitle"
            :source-url="summary.source"
            :reader-mode="isReaderMode"
            @share="copyLink"
            @open-source="openSource"
            @save="saveSummary"
          />
          <AppSummaryContent :content="summary.summary ?? ''" />
          <AppSummaryFooter
            :reader-mode="isReaderMode"
            @do-another="doAnother"
          />
        </template>
      </div>
    </article>
  </main>
</template>
